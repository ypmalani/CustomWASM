#!/usr/bin/env node
/**
 * Extract the EBNF grammar from .cursor/memory/architecture.md and emit a
 * structured language-reference markdown file for the playground Docs tab.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const architecturePath = join(root, ".cursor/memory/architecture.md");
const outPath = join(
  root,
  "src/playground/docs/language-reference.generated.md",
);

const SECTION_HEADERS = [
  {
    title: "Program",
    rules: ["program", "functionDecl", "paramList", "param"],
  },
  {
    title: "Types",
    rules: ["type"],
  },
  {
    title: "Statements",
    rules: [
      "block",
      "statement",
      "letStmt",
      "assignStmt",
      "lvalue",
      "ifStmt",
      "whileStmt",
      "returnStmt",
      "exprStmt",
    ],
  },
  {
    title: "Expressions",
    rules: [
      "expression",
      "logicalOr",
      "logicalAnd",
      "equality",
      "comparison",
      "additive",
      "multiplicative",
      "unary",
      "postfix",
      "call",
      "index",
      "argList",
      "primary",
      "arrayLiteral",
    ],
  },
];

function extractEbnf(markdown) {
  const match = markdown.match(/```ebnf\n([\s\S]*?)```/);
  if (!match) {
    throw new Error("No ```ebnf``` fence found in architecture.md");
  }
  return match[1].trimEnd();
}

/** Parse top-level `name = ... ;` productions (multi-line aware). */
function parseProductions(ebnf) {
  const productions = new Map();
  // Strip (* ... *) comments
  const cleaned = ebnf.replace(/\(\*[\s\S]*?\*\)/g, "");
  const re = /^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*([\s\S]*?)\s*;\s*$/gm;
  let m;
  while ((m = re.exec(cleaned)) !== null) {
    const name = m[1];
    const body = m[2].replace(/\s+/g, " ").trim();
    productions.set(name, body);
  }
  return productions;
}

function renderReference(productions) {
  const lines = [];
  lines.push("<!-- Generated by scripts/generate-lang-ref.mjs — do not edit. -->");
  lines.push("# CustomWASM Language Reference");
  lines.push("");
  lines.push(
    "Generated from the EBNF grammar in `.cursor/memory/architecture.md`.",
  );
  lines.push("");
  lines.push(
    "Whitespace and `//` line comments are skipped by the lexer. Identifiers may not be keywords.",
  );
  lines.push("");
  lines.push(
    "Entry point: a `fn main() -> i32` is required; the playground calls its export.",
  );
  lines.push("");

  const seen = new Set();
  for (const section of SECTION_HEADERS) {
    lines.push(`## ${section.title}`);
    lines.push("");
    for (const rule of section.rules) {
      const body = productions.get(rule);
      if (body === undefined) {
        throw new Error(`Missing production '${rule}' in extracted EBNF`);
      }
      lines.push(`### \`${rule}\``);
      lines.push("");
      lines.push("```ebnf");
      lines.push(`${rule} = ${body} ;`);
      lines.push("```");
      lines.push("");
      seen.add(rule);
    }
  }

  const extras = [...productions.keys()].filter((k) => !seen.has(k));
  if (extras.length > 0) {
    lines.push("## Other");
    lines.push("");
    for (const rule of extras) {
      lines.push(`### \`${rule}\``);
      lines.push("");
      lines.push("```ebnf");
      lines.push(`${rule} = ${productions.get(rule)} ;`);
      lines.push("```");
      lines.push("");
    }
  }

  return lines.join("\n");
}

const markdown = readFileSync(architecturePath, "utf8");
const ebnf = extractEbnf(markdown);
const productions = parseProductions(ebnf);
if (productions.size === 0) {
  throw new Error("Failed to parse any EBNF productions");
}

const required = [
  "program",
  "functionDecl",
  "ifStmt",
  "logicalOr",
  "arrayLiteral",
];
for (const name of required) {
  if (!productions.has(name)) {
    throw new Error(`Spot-check failed: missing rule '${name}'`);
  }
}

const output = renderReference(productions);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, output, "utf8");
console.log(`Wrote ${outPath} (${productions.size} productions)`);
